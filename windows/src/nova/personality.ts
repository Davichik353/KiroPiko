import { State } from "../core/state";
import { Speech } from "./voice/speech";

export const KIRO_LINES = {
  rest: ["Я рядом. Можно не спешить.", "Пока тихо — берегу ваши идеи.", "Проверю, не уснули ли пиксели.", "Маленькая пауза тоже часть работы.", "Код подождёт один спокойный вдох."],
  success: ["Готово! Можно выдохнуть.", "Ещё одна задача позади.", "Кажется, мы заслужили маленькую победу.", "Красиво получилось. Дайте пять!", "Сохраним этот хороший момент."],
  error: ["Спокойно, разберёмся по шагам.", "Ошибка — это подсказка, хотя и сердитая.", "Я рядом. Начнём с первой строки ошибки.", "Без паники: сначала посмотрим детали.", "Кажется, коду нужен ещё один разговор."],
  music: ["Под этот трек даже пиксели пританцовывают.", "Моя любимая музыка — та, под которую вам хорошо.", "Небольшой танец, и снова к делу.", "Ритм есть. Осталось поймать вдохновение.", "Я не диджей, но кнопку паузы найду."],
  return: ["Я снова рядом.", "Тихий режим окончен. Возвращаюсь.", "Не отвлекаю. Просто снова здесь.", "Продолжим, когда будете готовы.", "Капсула на месте, Киро тоже."],
} as const;
export function kiroLine(kind: keyof typeof KIRO_LINES, index = Math.floor(Math.random() * 5)): string {
  return KIRO_LINES[kind][Math.abs(index) % 5];
}
export function sayKiroLine() {
  if (State.novaQuietActive) return;
  const line = State.novaPhrase || kiroLine(State.novaMusicPlaying ? "music" : "rest");
  Speech.speak(line);
}
